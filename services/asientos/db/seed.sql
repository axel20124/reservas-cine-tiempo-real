-- Datos de prueba: 3 funciones (41, 42, 43), cada una con 8 filas x 12 asientos = 96 asientos.
-- Compatible con MySQL 5.7 y 8.x (no usa WITH RECURSIVE).
USE asientos_db;

DELETE FROM asientos;

INSERT INTO asientos (funcion_id, fila, numero)
SELECT fn.id, f.fila, n.numero
FROM (SELECT 41 AS id UNION ALL SELECT 42 UNION ALL SELECT 43) fn
CROSS JOIN (SELECT 'A' AS fila UNION ALL SELECT 'B' UNION ALL SELECT 'C' UNION ALL SELECT 'D'
            UNION ALL SELECT 'E' UNION ALL SELECT 'F' UNION ALL SELECT 'G' UNION ALL SELECT 'H') f
CROSS JOIN (SELECT 1 AS numero UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
            UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8
            UNION ALL SELECT 9 UNION ALL SELECT 10 UNION ALL SELECT 11 UNION ALL SELECT 12) n;
